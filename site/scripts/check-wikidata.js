const fs = require("node:fs");
const path = require("node:path");
const config = require("../config.js");

function parseWikipediaUrl(source) {
  const url = new URL(source);

  if (!url.hostname.endsWith(".wikipedia.org")) {
    throw new Error("wikiSource must currently be a Wikipedia article URL.");
  }

  const prefix = "/wiki/";
  if (!url.pathname.startsWith(prefix)) {
    throw new Error("wikiSource must look like https://en.wikipedia.org/wiki/Article_Title");
  }

  return {
    origin: url.origin,
    title: decodeURIComponent(url.pathname.slice(prefix.length)).replaceAll("_", " ")
  };
}

async function getJson(url) {
  const response = await fetch(url, {
    headers: {
      "User-Agent": "is-x-dead-checker/1.0 (GitHub Actions)"
    }
  });

  if (!response.ok) {
    throw new Error(`HTTP ${response.status} from ${url}`);
  }

  return response.json();
}

async function wikipediaTitleToWikidataId(source) {
  const { origin, title } = parseWikipediaUrl(source);
  const api = new URL("/w/api.php", origin);
  api.search = new URLSearchParams({
    action: "query",
    prop: "pageprops",
    titles: title,
    redirects: "1",
    format: "json",
    formatversion: "2"
  }).toString();

  const data = await getJson(api);
  const page = data?.query?.pages?.[0];
  const id = page?.pageprops?.wikibase_item;

  if (!id) {
    throw new Error(`No Wikidata item found for Wikipedia article: ${title}`);
  }

  return id;
}

async function getDateOfDeath(wikidataId) {
  const api = new URL("https://www.wikidata.org/w/api.php");
  api.search = new URLSearchParams({
    action: "wbgetentities",
    ids: wikidataId,
    props: "claims",
    format: "json"
  }).toString();

  const data = await getJson(api);
  const claims = data?.entities?.[wikidataId]?.claims ?? {};
  const deathClaims = claims.P570 ?? [];

  for (const claim of deathClaims) {
    const snak = claim?.mainsnak;
    if (snak?.snaktype === "value" && snak?.datavalue?.value?.time) {
      return snak.datavalue.value.time.replace(/^\+/, "");
    }
  }

  return null;
}

function writeStatus(status) {
  const file = path.join(__dirname, "..", "status.js");
  const contents = `// Generated by scripts/check-wikidata.js. Do not edit by hand.\nwindow.SITE_STATUS = ${JSON.stringify(status, null, 2)};\n`;
  fs.writeFileSync(file, contents);
}

(async () => {
  if (!config.wikiSource) throw new Error("config.js is missing wikiSource");

  const wikidataId = await wikipediaTitleToWikidataId(config.wikiSource);
  const dateOfDeath = await getDateOfDeath(wikidataId);

  const status = {
    answer: dateOfDeath ? "Yes" : "No",
    checkedAt: new Date().toISOString(),
    wikidataId,
    dateOfDeath
  };

  writeStatus(status);
  console.log(`${config.subject}: ${status.answer}. Wikidata ${wikidataId}${dateOfDeath ? `; P570=${dateOfDeath}` : "; no P570 claim"}`);
})().catch(error => {
  console.error(error);
  process.exit(1);
});
